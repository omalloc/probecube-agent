// enrollmentRequest is the payload sent to the control plane's enrollment
// endpoint. The serial number binds the resulting certificate to this machine.
type enrollmentRequest struct {
	Token string `json:"token"`
	SN    string `json:"sn"`
}

// enrollmentResponse carries freshly issued certificate material. The private
// key is generated by the control plane because the agent has no key yet.
type enrollmentResponse struct {
	CertPEM  string `json:"cert_pem"`
	KeyPEM   string `json:"key_pem"`
	CAPEM    string `json:"ca_pem"`
	NotAfter int64  `json:"not_after"`
	Serial   string `json:"serial"`
	Error    string `json:"error"`
}

// EnsureCertificate makes sure a usable client certificate exists before the
// agent dials NATS.
//
// When both certificate files are already present nothing happens. Otherwise the
// agent exchanges its enrollment token for a certificate and writes the files.
// This ordering matters: the NATS connection cannot be established without a
// certificate, so enrollment has to complete first.
func EnsureCertificate(ctx context.Context, c *conf.LeafNode, sn string) error {
	tlsCfg := c.GetTls()
	if tlsCfg == nil {
		return errors.New("leafnode.tls is required")
	}

	if fileExists(tlsCfg.GetCertFile()) && fileExists(tlsCfg.GetKeyFile()) {
		return nil
	}

	enroll := c.GetEnrollment()
	if enroll == nil || strings.TrimSpace(enroll.GetUrl()) == "" {
		return fmt.Errorf("no client certificate at %q and no leafnode.enrollment.url to obtain one",
			tlsCfg.GetCertFile())
	}

	token, err := readToken(enroll)
	if err != nil {
		return err
	}

	log.Info("enrolling node", "sn", sn, "url", enroll.GetUrl())

	resp, err := postEnrollment(ctx, enroll.GetUrl(), enrollmentRequest{Token: token, SN: sn})
	if err != nil {
		return err
	}
	if resp.Error != "" {
		return fmt.Errorf("enrollment refused: %s", resp.Error)
	}
	if resp.CertPEM == "" || resp.KeyPEM == "" {
		return errors.New("enrollment returned no certificate material")
	}

	if err := writeSecret(tlsCfg.GetCertFile(), []byte(resp.CertPEM)); err != nil {
		return fmt.Errorf("write certificate: %w", err)
	}
	if err := writeSecret(tlsCfg.GetKeyFile(), []byte(resp.KeyPEM)); err != nil {
		return fmt.Errorf("write private key: %w", err)
	}
	// Only write the CA when the operator has not supplied one; an explicit
	// path is authoritative.
	if !fileExists(tlsCfg.GetRootCa()) && resp.CAPEM != "" {
		if err := writeSecret(tlsCfg.GetRootCa(), []byte(resp.CAPEM)); err != nil {
			return fmt.Errorf("write root ca: %w", err)
		}
	}

	log.Info("enrollment complete", "serial", resp.Serial,
		"not_after", time.Unix(resp.NotAfter, 0).Format(time.RFC3339))
	return nil
}

func readToken(enroll *conf.Enrollment) (string, error) {
	if path := strings.TrimSpace(enroll.GetTokenFile()); path != "" {
		raw, err := os.ReadFile(path)
		if err != nil {
			return "", fmt.Errorf("read enrollment token file: %w", err)
		}
		token := strings.TrimSpace(string(raw))
		if token == "" {
			return "", fmt.Errorf("enrollment token file %q is empty", path)
		}
		return token, nil
	}
	if token := strings.TrimSpace(enroll.GetToken()); token != "" {
		return token, nil
	}
	return "", errors.New("leafnode.enrollment.token or token_file is required")
}

// postEnrollment calls the control plane's issuance endpoint.
//
// The connection is plain HTTPS with certificate verification left to the
// system trust store: at this point the agent has no client certificate, and the
// server certificate is what authenticates the control plane.
func postEnrollment(ctx context.Context, url string, payload enrollmentRequest) (*enrollmentResponse, error) {
	body, err := json.Marshal(payload)
	if err != nil {
		return nil, err
	}

	ctx, cancel := context.WithTimeout(ctx, 30*time.Second)
	defer cancel()

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, url, bytes.NewReader(body))
	if err != nil {
		return nil, err
	}
	req.Header.Set("Content-Type", "application/json")

	// Use a dedicated client so the agent's own probing TLS settings never leak
	// into this call.
	client := &http.Client{
		Timeout: 30 * time.Second,
		Transport: &http.Transport{
			TLSClientConfig: &tls.Config{MinVersion: tls.VersionTLS12},
		},
	}

	resp, err := client.Do(req)
	if err != nil {
		return nil, fmt.Errorf("enrollment request: %w", err)
	}
	defer resp.Body.Close()

	raw, err := io.ReadAll(io.LimitReader(resp.Body, 1<<20))
	if err != nil {
		return nil, fmt.Errorf("read enrollment response: %w", err)
	}

	var out enrollmentResponse
	if err := json.Unmarshal(raw, &out); err != nil {
		return nil, fmt.Errorf("decode enrollment response (status %d): %w", resp.StatusCode, err)
	}
	if resp.StatusCode != http.StatusOK && out.Error == "" {
		return nil, fmt.Errorf("enrollment failed with status %d", resp.StatusCode)
	}
	return &out, nil
}

// CurrentCertSerial returns the serial of the loaded client certificate, which
// the agent presents as its renewal identity.
func CurrentCertSerial(certFile string) (string, error) {
	raw, err := os.ReadFile(certFile)
	if err != nil {
		return "", err
	}
	block, _ := pem.Decode(raw)
	if block == nil {
		return "", errors.New("client certificate is not valid PEM")
	}
	cert, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		return "", err
	}
	return cert.SerialNumber.Text(16), nil
}

// CertNotAfter returns the expiry of the loaded client certificate.
func CertNotAfter(certFile string) (time.Time, error) {
	raw, err := os.ReadFile(certFile)
	if err != nil {
		return time.Time{}, err
	}
	block, _ := pem.Decode(raw)
	if block == nil {
		return time.Time{}, errors.New("client certificate is not valid PEM")
	}
	cert, err := x509.ParseCertificate(block.Bytes)
	if err != nil {
		return time.Time{}, err
	}
	return cert.NotAfter, nil
}

func fileExists(path string) bool {
	if strings.TrimSpace(path) == "" {
		return false
	}
	info, err := os.Stat(path)
	return err == nil && !info.IsDir()
}

// writeSecret writes certificate material with 0600 permissions, replacing the
// file atomically so a crash cannot leave a half-written key that the agent
// would then fail to load.
func writeSecret(path string, data []byte) error {
	dir := filepath.Dir(path)
	if err := os.MkdirAll(dir, 0o700); err != nil {
		return err
	}

	tmp, err := os.CreateTemp(dir, ".tmp-*")
	if err != nil {
		return err
	}
	tmpName := tmp.Name()
	defer os.Remove(tmpName)

	if err := tmp.Chmod(0o600); err != nil {
		tmp.Close()
		return err
	}
	if _, err := tmp.Write(data); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Sync(); err != nil {
		tmp.Close()
		return err
	}
	if err := tmp.Close(); err != nil {
		return err
	}
	return os.Rename(tmpName, path)
}
